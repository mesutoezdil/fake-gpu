#!/usr/bin/env python3
"""Write unsupported.c: a NOT_SUPPORTED stub for every AMD SMI function that
mock.c does not implement, so the library exports the whole ABI.

    cc -E -P amdsmi.h > /tmp/amdsmi.i
    ./generate-stubs.py /tmp/amdsmi.i

The input is the preprocessed header; preprocessing drops the CPU (ESMI)
half of the ABI, which needs a build flag the mock does not set.
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
FUNCTION = re.compile(r'amdsmi_status_t\s+(amdsmi_\w+)\s*\(([^;]*?)\)\s*;', re.S)
DEFINED = re.compile(r'^amdsmi_status_t\s+(amdsmi_\w+)\s*\(', re.M)


def stub(name, params):
    params = ' '.join(params.split())
    return f'amdsmi_status_t {name}({params}) {{\n    return AMDSMI_STATUS_NOT_SUPPORTED;\n}}\n'


def main(header):
    implemented = set(DEFINED.findall((HERE / 'mock.c').read_text()))
    seen, stubs = set(), []
    for name, params in FUNCTION.findall(Path(header).read_text()):
        if name not in implemented and name not in seen:
            seen.add(name)
            stubs.append(stub(name, params))
    (HERE / 'unsupported.c').write_text(
        '// SPDX-License-Identifier: AGPL-3.0-only\n'
        '// Generated by generate-stubs.py from the pinned AMD SMI header. Do not edit.\n'
        '#include "amdsmi.h"\n\n'
        '#pragma GCC diagnostic ignored "-Wunused-parameter"\n\n'
        + '\n'.join(stubs))
    print(f'{len(stubs)} stubs, {len(implemented)} implemented in mock.c')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
